#!/usr/bin/env python3
"""Regenerate a hash-pinned wheel set (BitBake SRC_URI include) for the target.

Resolves a requirements file's dependency closure for the *target* (aarch64,
the Yocto release's CPython and glibc) with pip's cross-platform resolver and
writes one SRC_URI entry (exact PyPI URL + sha256) per wheel.

    scripts/gen-wheels.py \
        --requirements apps/slate-agent/requirements-target.txt \
        --out meta-ha-slate/recipes-voice/slate-agent/slate-agent-wheels.inc

Why wheels: the wake word engines (pymicro-wakeword / pyopen-wakeword) bundle a
TensorFlow Lite C library and depend on numpy >= 2 and a C feature extractor.
Their sdists even ship an x86-64 build of the library, so a from-source recipe
silently produces a broken image. docs/SPEC.md ("Packaging strategy")
describes the path to fully native recipes.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import subprocess
import sys
import tempfile
import urllib.request


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--requirements", required=True, help="pip requirements file (pinned)")
    ap.add_argument("--python", default="3.12")
    ap.add_argument("--glibc", default="2.39")
    ap.add_argument("--arch", default="aarch64")
    ap.add_argument("--out", required=True, help="BitBake include to write")
    ap.add_argument("--var", default="SLATE_WHEELS", help="variable name for the SRC_URI list")
    a = ap.parse_args()

    with open(a.requirements) as f:
        deps = [ln.split("#")[0].strip() for ln in f if ln.split("#")[0].strip()]

    pyver = a.python.replace(".", "")
    major, minor = a.glibc.split(".")
    platforms = [f"manylinux_{major}_{m}_{a.arch}" for m in range(int(minor), 16, -1)] + [f"manylinux2014_{a.arch}"]

    with tempfile.TemporaryDirectory() as tmp:
        cmd = [sys.executable, "-m", "pip", "download", "--quiet", "--no-cache-dir", "-d", tmp,
               "--only-binary=:all:", "--implementation", "cp", "--python-version", a.python,
               "--abi", f"cp{pyver}", "--abi", "abi3", "--abi", "none"]
        for p in platforms + ["any"]:
            cmd += ["--platform", p]
        subprocess.run(cmd + deps, check=True)
        wheels = sorted(os.listdir(tmp))
        lines = [
            "# Generated by scripts/gen-wheels.py -- do not edit by hand.",
            f"# Target: cp{pyver} / glibc {a.glibc} / {a.arch}",
            "# Requirements: " + ", ".join(deps),
            "",
            f"{a.var} = \"\\",
        ]
        checks = []
        for w in wheels:
            dist, version = w.split("-")[:2]
            name = re.sub(r"[^A-Za-z0-9]", "_", dist.lower())
            with open(os.path.join(tmp, w), "rb") as f:
                sha = hashlib.sha256(f.read()).hexdigest()
            url = _pypi_url(dist, version, w, sha)
            lines.append(f"    {url};name={name};downloadfilename={w};unpack=0;subdir=wheels \\")
            checks.append(f'SRC_URI[{name}.sha256sum] = "{sha}"')
        lines.append('"')
        lines.append("")
        lines.extend(checks)
    with open(a.out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {len(wheels)} wheels to {os.path.relpath(a.out)}")


def _pypi_url(dist: str, version: str, filename: str, sha: str) -> str:
    """Exact, content-addressed files.pythonhosted.org URL for one wheel."""
    with urllib.request.urlopen(f"https://pypi.org/pypi/{dist}/{version}/json") as r:
        for f in json.load(r)["urls"]:
            if f["filename"] == filename:
                if f["digests"]["sha256"] != sha:
                    raise SystemExit(f"sha256 mismatch for {filename}")
                return f["url"]
    raise SystemExit(f"{filename} not found on PyPI")


if __name__ == "__main__":
    main()
