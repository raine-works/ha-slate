#!/usr/bin/env python3
"""Regenerate meta-ha-slate/recipes-voice/linux-voice-assistant/lva-wheels.inc.

Resolves Linux Voice Assistant's runtime dependency closure for the *target*
(aarch64, CPython of the Yocto release, glibc of the Yocto release) using pip's
cross-platform resolver, then writes one hash-pinned SRC_URI entry per wheel.

    scripts/gen-lva-wheels.py --lva-src ../linux-voice-assistant \
        --python 3.12 --glibc 2.39 --arch aarch64

Why wheels instead of one recipe per Python package: several dependencies are
native (numpy 2, aioesphomeapi, zeroconf, webrtc-noise-gain, netifaces2 (Rust),
pymicro-wakeword/pyopen-wakeword which bundle a TensorFlow Lite C library).
Upstream publishes manylinux aarch64 wheels for all of them; consuming those,
hash-pinned, is reproducible and keeps bring-up time sane. docs/SPEC.md
("Voice service -> Packaging strategy") describes the path to native recipes.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import subprocess
import sys
import tempfile
import tomllib
import urllib.request


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--lva-src", required=True, help="checkout of OHF-Voice/linux-voice-assistant")
    ap.add_argument("--python", default="3.12")
    ap.add_argument("--glibc", default="2.39")
    ap.add_argument("--arch", default="aarch64")
    ap.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "..", "meta-ha-slate",
                                                   "recipes-voice", "linux-voice-assistant", "lva-wheels.inc"))
    a = ap.parse_args()

    with open(os.path.join(a.lva_src, "pyproject.toml"), "rb") as f:
        deps = tomllib.load(f)["project"]["dependencies"]
    # Type stubs are dev-only noise in a runtime image.
    deps = [d for d in deps if not d.startswith("types-")]

    pyver = a.python.replace(".", "")
    major, minor = a.glibc.split(".")
    platforms = [f"manylinux_{major}_{m}_{a.arch}" for m in range(int(minor), 16, -1)] + [f"manylinux2014_{a.arch}"]

    with tempfile.TemporaryDirectory() as tmp:
        cmd = [sys.executable, "-m", "pip", "download", "--quiet", "--no-cache-dir", "-d", tmp,
               "--only-binary=:all:", "--implementation", "cp", "--python-version", a.python,
               "--abi", f"cp{pyver}", "--abi", "abi3", "--abi", "none"]
        for p in platforms + ["any"]:
            cmd += ["--platform", p]
        subprocess.run(cmd + deps, check=True)
        wheels = sorted(os.listdir(tmp))
        lines = [
            "# Generated by scripts/gen-lva-wheels.py -- do not edit by hand.",
            f"# Target: cp{pyver} / glibc {a.glibc} / {a.arch}",
            "# Requirements: " + ", ".join(deps),
            "",
            "LVA_WHEELS = \"\\",
        ]
        checks = []
        for w in wheels:
            dist, version = w.split("-")[:2]
            name = re.sub(r"[^A-Za-z0-9]", "_", dist.lower())
            with open(os.path.join(tmp, w), "rb") as f:
                sha = hashlib.sha256(f.read()).hexdigest()
            url = _pypi_url(dist, version, w, sha)
            lines.append(f"    {url};name={name};downloadfilename={w};unpack=0;subdir=wheels \\")
            checks.append(f'SRC_URI[{name}.sha256sum] = "{sha}"')
        lines.append('"')
        lines.append("")
        lines.extend(checks)
    with open(a.out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {len(wheels)} wheels to {os.path.relpath(a.out)}")


def _pypi_url(dist: str, version: str, filename: str, sha: str) -> str:
    """Exact, content-addressed files.pythonhosted.org URL for one wheel."""
    with urllib.request.urlopen(f"https://pypi.org/pypi/{dist}/{version}/json") as r:
        for f in json.load(r)["urls"]:
            if f["filename"] == filename:
                if f["digests"]["sha256"] != sha:
                    raise SystemExit(f"sha256 mismatch for {filename}")
                return f["url"]
    raise SystemExit(f"{filename} not found on PyPI")


if __name__ == "__main__":
    main()
